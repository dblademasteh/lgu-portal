/**
 * Generate the Kubernetes Secret for the portal.
 *
 * Replaces a committed `secret.yaml` whose values were the literal string
 * "REPLACE_WITH_GENERATED_SECRET". That file was one `kubectl apply` away from
 * a real incident: the app boots, SESSION_SECRET is a well-known string, and
 * every session cookie is forgeable.
 *
 * Usage:
 *   node scripts/gen-k8s-secret.mjs                  # manifest to stdout
 *   node scripts/gen-k8s-secret.mjs --apply          # pipe to kubectl apply
 *   node scripts/gen-k8s-secret.mjs --issuer https://portal.lgu.gov.ph
 *
 * Secrets go to stdout and nowhere else — no file in the repo, no shell
 * history. Redirect deliberately if your secret manager ingests a file.
 */

import { randomBytes, generateKeyPairSync } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const args = process.argv.slice(2);
const has = (flag) => args.includes(flag);
const valueOf = (flag, fallback) => {
  const index = args.indexOf(flag);
  return index !== -1 && args[index + 1] ? args[index + 1] : fallback;
};

/** 48 random bytes, base64. Comfortably past the 32-character minimum. */
const generate = () => randomBytes(48).toString('base64');

const sessionSecret = generate();
const oidcSigningSecret = generate();
const issuer = valueOf('--issuer', 'https://portal.lgu.gov.ph');
const namespace = valueOf('--namespace', 'lgu-portal');
const idpIssuer = valueOf('--idp-issuer', '');
const idpClientId = valueOf('--idp-client-id', '');
const idpClientSecret = valueOf('--idp-client-secret', '');
// src/lib/auth/users.ts reads this at module load and throws when it is unset,
// so omitting it turned every route that touches the user directory into a 500.
// Default to a random value nobody knows: the seeded demo accounts stay loaded
// (the module needs the string) but are unguessable in production.
const demoPassword = valueOf('--demo-password', generate());

// The RS256 signing key. Every replica must sign with the same key, or
// `GET /api/oidc/jwks` publishes whichever pod answers it and a client that
// cached the set gets a `kid` it has never seen and rejects valid tokens.
// Generated once here and mounted on all replicas; a restart no longer
// invalidates outstanding tokens either.
const signingKeyPem = valueOf(
  '--signing-key',
  generateKeyPairSync('rsa', { modulusLength: 2048, publicExponent: 0x10001 }).privateKey
    .export({ type: 'pkcs8', format: 'pem' })
    .toString(),
);

if (sessionSecret.length < 32) {
  console.error('Generated SESSION_SECRET is too short; refusing to emit.');
  process.exit(1);
}

const lines = [
  '# Generated by scripts/gen-k8s-secret.mjs — do not commit.',
  'apiVersion: v1',
  'kind: Secret',
  'metadata:',
  `  name: lgu-portal-secrets`,
  `  namespace: ${namespace}`,
  'type: Opaque',
  'stringData:',
  `  SESSION_SECRET: "${sessionSecret}"`,
  `  OIDC_SIGNING_SECRET: "${oidcSigningSecret}"`,
  `  OIDC_ISSUER: "${issuer}"`,
  `  DEMO_PASSWORD: "${demoPassword}"`,
  // Escaped newlines: a secretKeyRef cannot carry a multi-line value.
  `  OIDC_SIGNING_PRIVATE_KEY: "${signingKeyPem.trimEnd().replace(/\n/g, '\\n')}"`,
];

if (idpIssuer) lines.push(`  IDP_ISSUER: "${idpIssuer}"`);
if (idpClientId) lines.push(`  IDP_CLIENT_ID: "${idpClientId}"`);
if (idpClientSecret) lines.push(`  IDP_CLIENT_SECRET: "${idpClientSecret}"`);

const manifest = lines.join('\n') + '\n';

if (!has('--apply')) {
  console.log(manifest);
  process.exit(0);
}

const kubectl = spawnSync('kubectl', ['apply', '-f', '-'], {
  input: manifest,
  stdio: ['pipe', 'inherit', 'inherit'],
  shell: process.platform === 'win32',
});

if (kubectl.error) {
  console.error(`Could not run kubectl: ${kubectl.error.message}`);
  console.error('Generated manifest was not applied. Re-run without --apply and pipe it yourself.');
  process.exit(1);
}

if (kubectl.status !== 0) {
  console.error('kubectl apply failed. The secret was NOT created.');
  process.exit(kubectl.status ?? 1);
}

console.error(`Applied lgu-portal-secrets to ${namespace}. Rolling the deployment restarts pods.`);
